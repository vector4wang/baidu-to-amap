function convertor(x, y, c) {
  let px = c[0] + c[1] * Math.abs(x);
  const cc = Math.abs(y) / c[9];
  let py = c[2] + c[3] * cc + c[4] * cc * cc + c[5] * cc ** 3 + c[6] * cc ** 4 + c[7] * cc ** 5 + c[8] * cc ** 6;
  px *= x < 0 ? -1 : 1;
  py *= y < 0 ? -1 : 1;
  return [px, py];
}
